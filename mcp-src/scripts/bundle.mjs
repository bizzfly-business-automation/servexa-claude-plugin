/**
 * Builds the one file the Claude plugin ships: plugins/servexa/mcp/servexa-mcp.mjs (the MCP server, every dependency
 * inlined - there are none beyond Node itself) and mcp/RELEASE.json (version + SHA-256 of that file).
 *
 *   node scripts/bundle.mjs           write both files
 *   node scripts/bundle.mjs --check   build in memory and fail (exit 1) if the committed files differ - CI runs this
 *
 * Nothing is published to a package registry: the bundle is committed into the plugin directory and travels with the plugin.
 * esbuild is a build-time tool only (a devDependency of mcp-src); it is not part of the shipped file.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const packageDir = resolve(here, '..');
const repoRoot = resolve(packageDir, '..');
const outDir = join(repoRoot, 'plugins', 'servexa', 'mcp');
const bundlePath = join(outDir, 'servexa-mcp.mjs');
const releasePath = join(outDir, 'RELEASE.json');

function loadEsbuild() {
  try {
    return createRequire(join(packageDir, 'package.json'))('esbuild');
  } catch {
    throw new Error('esbuild was not found. Run "npm install" in mcp-src first.');
  }
}

const version = /export const PLUGIN_VERSION = '([^']+)'/.exec(readFileSync(join(packageDir, 'src', 'version.ts'), 'utf8'))?.[1];
if (!version) throw new Error('PLUGIN_VERSION not found in src/version.ts');

const esbuild = loadEsbuild();
const result = await esbuild.build({
  absWorkingDir: packageDir, // comment paths in the bundle are relative to this, so the output does not depend on where the script is run from
  entryPoints: ['src/main.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  write: false,
  minify: false, // readable on purpose: the bundle is reviewed in pull requests
  legalComments: 'none',
  logLevel: 'silent',
  banner: { js: `// servexa-mcp ${version} - generated by mcp-src/scripts/bundle.mjs from mcp-src/src. Do not edit by hand.\n` },
});
const bundle = result.outputFiles[0].text.replace(/\r\n/g, '\n');
const release = `${JSON.stringify({ pluginVersion: version, bundle: 'servexa-mcp.mjs', sha256: createHash('sha256').update(bundle).digest('hex'), node: '>=20' }, null, 2)}\n`;

const read = (path) => (existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : null);

if (process.argv.includes('--check')) {
  const problems = [];
  if (read(bundlePath) !== bundle) problems.push('plugins/servexa/mcp/servexa-mcp.mjs differs from a fresh build of mcp-src/src');
  if (read(releasePath) !== release) problems.push('plugins/servexa/mcp/RELEASE.json differs from a fresh build');
  if (problems.length) {
    console.error(`${problems.join('\n')}\nRun: npm run build (in mcp-src)`);
    process.exit(1);
  }
  console.log(`servexa-mcp ${version}: the committed bundle matches its sources.`);
} else {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(bundlePath, bundle, 'utf8');
  writeFileSync(releasePath, release, 'utf8');
  console.log(`servexa-mcp ${version}: wrote ${bundlePath} (${bundle.length} bytes) and RELEASE.json`);
}
